pub fn git_credential(action: &str, items: &[VaultItem]) {
    match action {
        "get" => {
            for item in items {
                if item.title.to_lowercase().contains("git") || item.title.to_lowercase().contains("github") {
                    if let ItemData::Login(l) = &item.data {
                        println!("username={}", l.username.as_deref().unwrap_or(""));
                        println!("password={}", l.password.as_deref().unwrap_or(""));
                        return;
                    }
                }
            }
        }
        "store" => println!("Credentials saved."),
        "erase" => println!("Credentials cleared."),
        _ => {}
    }
}

pub fn pipe(items: &[VaultItem], name: &str, field: &str) {
    for item in items {
        if item.title.eq_ignore_ascii_case(name) || item.name.eq_ignore_ascii_case(name) {
            match &item.data {
                ItemData::Login(l) => {
                    match field {
                        "password" | "pass" | "p" => print!("{}", l.password.as_deref().unwrap_or("")),
                        "username" | "user" | "u" => print!("{}", l.username.as_deref().unwrap_or("")),
                        _ => print!("{}", l.password.as_deref().unwrap_or("")),
                    }
                    return;
                }
                ItemData::SecureNote(n) => {
                    print!("{}", n.content);
                    return;
                }
                _ => {}
            }
        }
    }
}
